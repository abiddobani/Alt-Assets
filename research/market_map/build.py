"""Build the readable views of the alternative assets market map.

market_map.csv is the source of truth. This script:
  1. recomputes share_of_group_pct from g20_size_usd_bn and writes it back to the CSV,
  2. writes market_map.md (the GitHub view),
  3. optionally writes an Excel copy:  python build.py --xlsx path/to/market_map.xlsx

Fields named in a row's estimated_fields column are shown with a leading "≈".
"""

import argparse
import csv
from collections import OrderedDict
from pathlib import Path

HERE = Path(__file__).resolve().parent
TABLE = HERE / "market_map.csv"
SOURCES = HERE / "sources.csv"
VIEW = HERE / "market_map.md"

# estimated_fields token -> CSV columns it covers
ESTIMATE_TOKENS = {
    "share": ["share_of_group_pct"],
    "g20_size": ["g20_size_usd_bn"],
    "canada_size": ["canada_size_usd_bn"],
    "duration": ["duration_years"],
    "return_20y": ["return_20y_pct"],
    "cash_yield": ["cash_yield_pct"],
    "fees": ["mgmt_fee", "performance_fee"],
}

MAIN_COLUMNS = [
    ("type", "Equity / Debt"),
    ("asset_class", "Asset class"),
    ("subgroup", "Subgroup"),
    ("share_of_group_pct", "% of asset class"),
    ("g20_size_usd_bn", "G20 size (USD bn)"),
    ("canada_size_usd_bn", "Canada size (USD bn)"),
    ("duration_years", "Duration (yrs)"),
    ("return_20y_pct", "20-yr return (% p.a.)"),
    ("fees", "Fees (management / performance)"),
]


def read_csv(path):
    with open(path, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        return reader.fieldnames, list(reader)


def num(value):
    return float(value) if str(value).strip() not in ("", "n/a") else None


def estimated_columns(row):
    cols = set()
    for token in row["estimated_fields"].split(";"):
        cols.update(ESTIMATE_TOKENS.get(token.strip(), []))
    return cols


def recompute_shares(rows):
    totals = {}
    for r in rows:
        totals[r["asset_class"]] = totals.get(r["asset_class"], 0) + (num(r["g20_size_usd_bn"]) or 0)
    for r in rows:
        size = num(r["g20_size_usd_bn"])
        total = totals[r["asset_class"]]
        r["share_of_group_pct"] = f"{100 * size / total:.1f}" if size is not None and total else ""


def groups(rows):
    out = OrderedDict()
    for r in rows:
        out.setdefault(r["asset_class"], []).append(r)
    return out


def fmt_number(value, decimals):
    v = num(value)
    if v is None:
        return "n/a"
    return f"{v:,.{decimals}f}"


def cell(row, col):
    est = col in estimated_columns(row) or (col == "fees" and "mgmt_fee" in estimated_columns(row))
    if col == "fees":
        text = f"{row['mgmt_fee']} / {row['performance_fee']}"
    elif col in ("g20_size_usd_bn", "canada_size_usd_bn"):
        text = fmt_number(row[col], 0)
    elif col in ("share_of_group_pct", "duration_years", "return_20y_pct", "cash_yield_pct"):
        text = fmt_number(row[col], 1)
    else:
        text = row[col]
    if est and text != "n/a":
        text = "≈ " + text
    return text


def weighted(rows, col):
    pairs = [(num(r["g20_size_usd_bn"]), num(r[col])) for r in rows]
    pairs = [(w, v) for w, v in pairs if w and v is not None]
    if not pairs:
        return None
    return sum(w * v for w, v in pairs) / sum(w for w, _ in pairs)


def md_escape(text):
    return str(text).replace("|", "\\|")


def write_markdown(rows, sources):
    lines = []
    add = lines.append
    add("# Alternative assets market map (draft)")
    add("")
    add("Generated by `build.py` from `market_map.csv`. Edit the CSV, then run "
        "`python research/market_map/build.py`. Do not edit this file by hand.")
    add("")
    add("**≈ marks an estimate.** Unmarked figures come straight from the cited source. "
        "Sizes are USD bn; G20 means the 19 member countries plus the EU. Column definitions "
        "and open questions are in [README.md](README.md).")
    add("")
    add("## Table")
    add("")
    add("| " + " | ".join(h for _, h in MAIN_COLUMNS) + " |")
    add("|" + "|".join(["---"] * 3 + ["---:"] * 5 + ["---"]) + "|")
    for asset_class, members in groups(rows).items():
        for r in members:
            add("| " + " | ".join(md_escape(cell(r, c)) for c, _ in MAIN_COLUMNS) + " |")
        g20 = sum(num(r["g20_size_usd_bn"]) or 0 for r in members)
        ca = sum(num(r["canada_size_usd_bn"]) or 0 for r in members)
        dur = weighted(members, "duration_years")
        ret = weighted(members, "return_20y_pct")
        add(f"| | **{asset_class} total** | | **100.0** | **{g20:,.0f}** | **{ca:,.0f}** | "
            f"*{dur:.1f} avg* | *{ret:.1f} avg* | |")
    add("")
    add("Totals sum the rows. Averages are weighted by today's G20 sizes and inherit any estimates "
        "in the rows, so they can differ from the index: for Public Equity the 20-yr average is "
        "pulled up by today's large IT weight (MSCI ACWI itself ≈ 8.2% p.a.).")
    add("")

    add("## How each asset class is measured")
    add("")
    for asset_class, members in groups(rows).items():
        first = members[0]
        add(f"### {asset_class}")
        add("")
        add(f"- **Size ({md_escape(first['size_as_of'])}):** {md_escape(first['size_basis'])}")
        bases = OrderedDict()
        for r in members:
            bases.setdefault(("duration", r["duration_basis"]), []).append(r["subgroup"])
        for r in members:
            bases.setdefault(("return", f"{r['return_basis']} ({r['return_period']}; "
                                        f"{'net' if r['return_net_of_fees'] == 'Y' else 'gross'} of fees)"), []).append(r["subgroup"])
        for (kind, text), subs in bases.items():
            scope = "" if len(subs) == len(members) else f" ({', '.join(subs)})"
            label = "Duration" if kind == "duration" else "20-yr return"
            add(f"- **{label}{scope}:** {md_escape(text)}")
        add("")

    add("## Row details")
    add("")
    add("| ID | Subgroup | Definition | Cash yield (%) | Cash yield basis | Confidence | Sources | Notes |")
    add("|---|---|---|---:|---|---|---|---|")
    for r in rows:
        add("| " + " | ".join(md_escape(x) for x in [
            r["id"], r["subgroup"], r["subgroup_definition"], cell(r, "cash_yield_pct"),
            r["cash_yield_basis"], r["confidence"], r["sources"], r["notes"],
        ]) + " |")
    add("")

    add("## Sources")
    add("")
    add("| ID | Publisher | Title | Year | Used for |")
    add("|---|---|---|---|---|")
    for s in sources:
        title = f"[{md_escape(s['title'])}]({s['url']})" if s["url"] else md_escape(s["title"])
        add(f"| {s['id']} | {md_escape(s['publisher'])} | {title} | {s['year']} | {md_escape(s['used_for'])} |")
    add("")
    VIEW.write_text("\n".join(lines), encoding="utf-8")


def write_xlsx(rows, fieldnames, sources, path):
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, PatternFill
    from openpyxl.utils import get_column_letter

    est_font = Font(italic=True, color="1F5FBF")
    head_font = Font(bold=True, color="FFFFFF")
    head_fill = PatternFill("solid", fgColor="1F3864")
    total_fill = PatternFill("solid", fgColor="E7ECF5")

    wb = Workbook()
    ws = wb.active
    ws.title = "Table"
    ws.append(["Blue italic = estimate. Sizes in USD bn. Source of truth: research/market_map/market_map.csv"])
    ws["A1"].font = Font(italic=True)
    headers = [h for _, h in MAIN_COLUMNS] + ["Cash yield (%)", "Confidence", "ID"]
    ws.append(headers)
    for c in range(1, len(headers) + 1):
        ws.cell(row=2, column=c).font = head_font
        ws.cell(row=2, column=c).fill = head_fill
        ws.cell(row=2, column=c).alignment = Alignment(wrap_text=True, vertical="top")
    numeric = {"share_of_group_pct": "0.0", "g20_size_usd_bn": "#,##0", "canada_size_usd_bn": "#,##0",
               "duration_years": "0.0", "return_20y_pct": "0.0", "cash_yield_pct": "0.0"}
    for asset_class, members in groups(rows).items():
        for r in members:
            est = estimated_columns(r)
            values, cols = [], [c for c, _ in MAIN_COLUMNS] + ["cash_yield_pct", "confidence", "id"]
            for c in cols:
                if c == "fees":
                    values.append(f"{r['mgmt_fee']} / {r['performance_fee']}")
                elif c in numeric:
                    values.append(num(r[c]))
                else:
                    values.append(r[c])
            ws.append(values)
            for i, c in enumerate(cols, start=1):
                x = ws.cell(row=ws.max_row, column=i)
                if c in numeric:
                    x.number_format = numeric[c]
                if c in est or (c == "fees" and "mgmt_fee" in est):
                    x.font = est_font
                x.alignment = Alignment(wrap_text=(c == "fees"), vertical="top")
        ws.append(["", f"{asset_class} total", "", 100.0,
                   sum(num(r["g20_size_usd_bn"]) or 0 for r in members),
                   sum(num(r["canada_size_usd_bn"]) or 0 for r in members),
                   weighted(members, "duration_years"), weighted(members, "return_20y_pct")])
        for i in range(1, len(headers) + 1):
            x = ws.cell(row=ws.max_row, column=i)
            x.font = Font(bold=True)
            x.fill = total_fill
            if 4 <= i <= 8:
                x.number_format = ["0.0", "#,##0", "#,##0", "0.0", "0.0"][i - 4]
    for i, w in enumerate([9, 22, 32, 10, 12, 12, 10, 12, 60, 10, 11, 10], start=1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = "D3"

    detail = wb.create_sheet("Details")
    detail.append(fieldnames)
    for r in rows:
        detail.append([num(r[c]) if c in numeric else r[c] for c in fieldnames])
    for c in range(1, len(fieldnames) + 1):
        detail.cell(row=1, column=c).font = Font(bold=True)
    detail.freeze_panes = "E2"

    src = wb.create_sheet("Sources")
    src.append(list(sources[0].keys()))
    for s in sources:
        src.append(list(s.values()))
    for c in range(1, len(sources[0]) + 1):
        src.cell(row=1, column=c).font = Font(bold=True)
    wb.save(path)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--xlsx", help="also write an Excel copy to this path")
    args = parser.parse_args()

    fieldnames, rows = read_csv(TABLE)
    _, sources = read_csv(SOURCES)
    known = {s["id"] for s in sources}
    for r in rows:
        missing = [s.strip() for s in r["sources"].split(";") if s.strip() and s.strip() not in known]
        if missing:
            raise SystemExit(f"{r['id']}: unknown source id(s) {missing}")

    recompute_shares(rows)
    with open(TABLE, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    write_markdown(rows, sources)
    if args.xlsx:
        write_xlsx(rows, fieldnames, sources, args.xlsx)
    print(f"{len(rows)} rows -> {VIEW.name}" + (f", {args.xlsx}" if args.xlsx else ""))


if __name__ == "__main__":
    main()
